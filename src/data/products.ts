import type {
  Brand,
  Category,
  ColorFamily,
  Product,
  ProductBadge,
  ProductImage,
  ProductSize,
  SizeSystem,
} from "@/types/product";

/**
 * Catálogo mock da Fase 2 (27 produtos). Na Fase 4 vira o seed do Prisma.
 * Fotos: Unsplash (licença livre), ilustrativas — ver docs/creditos-imagens.md.
 */

const U = "https://unsplash.com/photos/";

function img(file: string, alt: string, width: number, height: number, credit: string): ProductImage {
  return { src: `/images/products/${file}.jpg`, alt, width, height, kind: "photo", credit: U + credit };
}

const sneakerLabels = ["37", "38", "39", "40", "41", "42", "43", "44"] as const;
const apparelLabels = ["P", "M", "G", "GG"] as const;

function stockFor(labels: readonly string[], stock: readonly number[]): ProductSize[] {
  return labels.map((label, index) => ({ label, stock: stock[index] ?? 0 }));
}

type Seed = {
  slug: string;
  name: string;
  shortName: string;
  brand: Brand;
  category: Category;
  type: string;
  colorway: string;
  colors: ColorFamily[];
  sku: string;
  description: string;
  details: string[];
  price: number;
  compareAtPrice?: number;
  images: ProductImage[];
  stock: number[];
  releasedAt: string;
  popularity: number;
  badge?: ProductBadge;
};

function sizeSystemFor(category: Category, stock: number[]): SizeSystem {
  if (category === "sneakers") return "sneaker";
  if (category === "roupas") return "apparel";
  return stock.length > 1 ? "apparel" : "one-size";
}

function build(seed: Seed, index: number): Product {
  const sizeSystem = sizeSystemFor(seed.category, seed.stock);
  const labels =
    sizeSystem === "sneaker" ? sneakerLabels : sizeSystem === "apparel" ? apparelLabels : (["U"] as const);
  return {
    id: `p-${String(index + 1).padStart(3, "0")}`,
    slug: seed.slug,
    name: seed.name,
    shortName: seed.shortName,
    brand: seed.brand,
    category: seed.category,
    type: seed.type,
    colorway: seed.colorway,
    colors: seed.colors,
    sku: seed.sku,
    description: seed.description,
    details: seed.details,
    price: seed.price,
    compareAtPrice: seed.compareAtPrice,
    images: seed.images,
    sizeSystem,
    sizes: stockFor(labels, seed.stock),
    releaseYear: Number(seed.releasedAt.slice(0, 4)),
    releasedAt: seed.releasedAt,
    popularity: seed.popularity,
    badge: seed.badge,
  };
}

