const U = "https://unsplash.com/photos/";

const DEMO_BRAND = "nada mais";

function img(file: string, alt: string, width: number, height: number, credit: string): ProductImage {
  return { src: `/images/products/${file}.jpg`, alt, width, height, kind: "photo", credit: U + credit };
}

const sneakerLabels = ["37", "38", "39", "40", "41", "42", "43", "44"] as const;
const apparelLabels = ["P", "M", "G", "GG"] as const;

type Seed = Omit<Product, "id" | "sizeSystem" | "sizes" | "releaseYear"> & { stock: number[] };

function sizeSystemFor(category: Category, stock: number[]): SizeSystem {
  if (category === "sneakers") return "sneaker";
  if (category === "roupas") return "apparel";
  return stock.length > 1 ? "apparel" : "one-size";
}

function build(seed: Seed, index: number): Product {
  const { stock, ...rest } = seed;
  const sizeSystem = sizeSystemFor(seed.category, stock);
  const labels: readonly string[] =
    sizeSystem === "sneaker" ? sneakerLabels : sizeSystem === "apparel" ? apparelLabels : ["U"];
  const sizes: ProductSize[] = labels.map((label, i) => ({ label, stock: stock[i] ?? 0 }));
  return {
    ...rest,
    id: `p-${String(index + 1).padStart(3, "0")}`,
    sizeSystem,
    sizes,
    releaseYear: Number(seed.releasedAt.slice(0, 4)),
  };
}

